import SwiftUI

struct SpeedTestView: View {
    @EnvironmentObject private var tester: InternetSpeedTester
    @EnvironmentObject private var monitor: WiFiMonitor

    private let columns = [GridItem(.adaptive(minimum: 150, maximum: 240), spacing: UI.gap)]

    var body: some View {
        ScrollView {
            VStack(alignment: .leading, spacing: UI.gap) {
                introduction
                measurementCard
                if !tester.history.isEmpty { historyCard }
            }
            .padding(UI.gap)
        }
        .background(Color(nsColor: .underPageBackgroundColor))
    }

    private var introduction: some View {
        Card("Internet speed test", systemImage: "speedometer") {
            VStack(alignment: .leading, spacing: 10) {
                Text("Measure the current Internet path from this Mac to Cloudflare’s nearest edge. Results include idle latency, jitter, download speed, and upload speed. This is not the raw Wi-Fi link rate, and a VPN or proxy can become part of the measured path.")
                    .font(.system(size: 11.5))
                    .fixedSize(horizontal: false, vertical: true)

                HStack(alignment: .top, spacing: 8) {
                    Image(systemName: "arrow.up.arrow.down.circle.fill")
                        .foregroundStyle(.orange)
                    Text("A test transfers up to about 120 MB. Download data is discarded; upload data is generated random bytes—not your files. Cloudflare can see your public IP and normal request metadata. No SSID, BSSID, labels, notes, or walkthroughs are sent.")
                        .font(.system(size: 10.5))
                        .fixedSize(horizontal: false, vertical: true)
                }
                .padding(9)
                .background(Color.orange.opacity(0.10), in: RoundedRectangle(cornerRadius: 8))

                HStack(spacing: 8) {
                    if tester.isRunning {
                        Button("Cancel", role: .cancel) { tester.cancel() }
                            .controlSize(.small)
                    } else {
                        Button("Start Speed Test") {
                            tester.start(networkName: monitor.current?.ssid)
                        }
                        .buttonStyle(.borderedProminent)
                        .controlSize(.small)
                    }
                    Link("About Cloudflare Speed Test",
                         destination: URL(string: "https://speed.cloudflare.com")!)
                        .font(.system(size: 10.5))
                    Spacer()
                    if let ssid = monitor.current?.ssid {
                        Text("Wi-Fi: \(ssid)")
                            .font(.system(size: 10.5))
                            .foregroundStyle(.secondary)
                            .lineLimit(1)
                    }
                }
            }
        }
    }

    private var measurementCard: some View {
        Card("Current result", systemImage: "gauge.with.dots.needle.67percent") {
            VStack(alignment: .leading, spacing: 12) {
                LazyVGrid(columns: columns, alignment: .leading, spacing: UI.gap) {
                    metric("Latency", value: tester.latencyMS.map { format($0, suffix: "ms") } ?? "—",
                           detail: "Round trip while idle", symbol: "clock.arrow.circlepath")
                    metric("Jitter", value: tester.jitterMS.map { format($0, suffix: "ms") } ?? "—",
                           detail: "Variation between latency checks", symbol: "waveform.path")
                    metric("Download", value: tester.downloadMbps.map { format($0, suffix: "Mbps") } ?? "—",
                           detail: "Cloudflare edge to this Mac", symbol: "arrow.down.circle")
                    metric("Upload", value: tester.uploadMbps.map { format($0, suffix: "Mbps") } ?? "—",
                           detail: "Generated bytes to Cloudflare", symbol: "arrow.up.circle")
                }

                if tester.isRunning {
                    VStack(alignment: .leading, spacing: 5) {
                        ProgressView(value: tester.progress)
                        HStack {
                            Text(tester.stage)
                            Spacer()
                            Text("\(Int(tester.progress * 100))%")
                        }
                        .font(.system(size: 10.5))
                        .foregroundStyle(.secondary)
                    }
                } else {
                    HStack(spacing: 6) {
                        Circle()
                            .fill(tester.errorMessage == nil ? Color.secondary : Color.orange)
                            .frame(width: 7, height: 7)
                        Text(tester.stage)
                            .font(.system(size: 10.5, weight: .medium))
                            .foregroundStyle(.secondary)
                    }
                }

                if let error = tester.errorMessage {
                    HStack(alignment: .top, spacing: 7) {
                        Image(systemName: "exclamationmark.triangle.fill").foregroundStyle(.orange)
                        Text(error).font(.system(size: 11)).fixedSize(horizontal: false, vertical: true)
                    }
                    .padding(9)
                    .background(Color.orange.opacity(0.10), in: RoundedRectangle(cornerRadius: 8))
                }
            }
        }
    }

    private var historyCard: some View {
        Card("This session", systemImage: "clock.arrow.2.circlepath") {
            VStack(spacing: 0) {
                ForEach(Array(tester.history.enumerated()), id: \.element.id) { index, result in
                    if index > 0 { Divider() }
                    HStack(spacing: 14) {
                        VStack(alignment: .leading, spacing: 2) {
                            Text(Fmt.stamp.string(from: result.date))
                                .font(.system(size: 10.5, weight: .medium))
                            HStack(spacing: 5) {
                                if let network = result.networkName { Text(network) }
                                if let edge = result.edgeLocation { Text("· Edge \(edge)") }
                            }
                            .font(.system(size: 9.5))
                            .foregroundStyle(Color.subtle)
                        }
                        Spacer()
                        historyValue("Ping", result.latencyMS, "ms")
                        historyValue("Down", result.downloadMbps, "Mbps")
                        historyValue("Up", result.uploadMbps, "Mbps")
                        Text(ByteCountFormatter.string(
                            fromByteCount: result.bytesDownloaded + result.bytesUploaded,
                            countStyle: .file))
                            .font(.system(size: 9.5, design: .monospaced))
                            .foregroundStyle(Color.subtle)
                            .frame(width: 64, alignment: .trailing)
                            .help("Total test traffic")
                    }
                    .padding(.vertical, 8)
                }
            }
        }
    }

    private func metric(_ title: String, value: String, detail: String, symbol: String) -> some View {
        HStack(alignment: .top, spacing: 8) {
            Image(systemName: symbol)
                .font(.system(size: 14))
                .foregroundStyle(.blue)
                .frame(width: 18)
            VStack(alignment: .leading, spacing: 2) {
                Text(value)
                    .font(.system(size: 19, weight: .semibold, design: .rounded))
                    .monospacedDigit()
                Text(title.uppercased())
                    .font(.system(size: 9, weight: .semibold)).tracking(0.4)
                    .foregroundStyle(.secondary)
                Text(detail)
                    .font(.system(size: 9.5)).foregroundStyle(Color.subtle)
                    .fixedSize(horizontal: false, vertical: true)
            }
        }
        .frame(maxWidth: .infinity, alignment: .leading)
        .padding(10)
        .background(Color(nsColor: .controlBackgroundColor), in: RoundedRectangle(cornerRadius: 8))
    }

    private func historyValue(_ title: String, _ value: Double, _ unit: String) -> some View {
        VStack(alignment: .trailing, spacing: 1) {
            Text(format(value, suffix: unit))
                .font(.system(size: 10.5, weight: .medium, design: .monospaced))
            Text(title).font(.system(size: 9)).foregroundStyle(Color.subtle)
        }
        .frame(width: 78, alignment: .trailing)
    }

    private func format(_ value: Double, suffix: String) -> String {
        let decimals = value >= 100 ? 0 : 1
        return String(format: "%.*f %@", decimals, value, suffix)
    }
}
